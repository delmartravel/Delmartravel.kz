  function slugifyHotelName(hotelName) {
    return String(hotelName || "")
      .trim()
      .toLowerCase()
      .replace(/&/g, "and")
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^-+|-+$/g, "");
  }

  function normalizeSlug(slug) {
    return String(slug || "")
      .trim()
      .toLowerCase()
      .replace(/^\/+|\/+$/g, "")
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^-+|-+$/g, "");
  }

  function getHotelSlug(hotelName) {
    return normalizeSlug(HOTEL_IMAGE_SLUGS[hotelName] || slugifyHotelName(hotelName));
  }

  function ensureList(value, fallback = []) {
    if (Array.isArray(value)) return value.filter(Boolean);
    if (value) return [value];
    return fallback;
  }

  function getHotelCatalogImagesBySlug(slug) {
    const safeSlug = normalizeSlug(slug);
    if (!safeSlug) return [];
    return ["01.jpg", "02.jpg", "03.jpg"].map(fileName =>
      `./assets/images/catalog/hotels/${safeSlug}/${fileName}`
    );
  }

  function getHotelCatalogImages(hotelName) {
    return getHotelCatalogImagesBySlug(getHotelSlug(hotelName));
  }

